#!/usr/bin/env python3
"""Link previews for WhatsApp / Facebook.

Preview bots read only the static HTML of a link and never see what follows the #, which is
where the app keeps its state. So a shared plan goes out through plan/<n>/ (n = how many events
are in it): a tiny page with its own og tags that sends the visitor on to the app, # and all.

Writes og.jpg (the app), og-plan.jpg (a plan) and plan/index.html, plan/1..MAX/index.html.
The images are real screenshots of the app at a busy hour, under a title band.

    python3 tools/make_share.py            # pages + images
    python3 tools/make_share.py --pages    # pages only (no browser)
"""
import base64, functools, http.server, sys, threading
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = 'https://orimosenzon.github.io/fun/vibe_coding/hanadiv/'
MAX = 60
W, H, BAND = 1200, 630, 132
SHOT = {'day': '30', 't': '20:30'}           # Friday evening: the map is at its fullest
NOW_UTC = '2026-10-30T18:30:00Z'             # the same moment, so "now" agrees with it


def page(n=None):
    title = f'התוכנית שלי בדרך הנדיב · {n} אירועים' if n else 'התוכנית שלי בפסטיבל דרך הנדיב'
    desc = ('האירועים שבחרתי בפסטיבל, על מפה ובלוח זמנים, עם המסלול ביניהם. '
            'בלחיצה אחת אפשר לצרף אותם לתוכנית שלך.')
    url = BASE + (f'plan/{n}/' if n else 'plan/')
    up = '../../' if n else '../'
    return f'''<!doctype html>
<!-- generated by tools/make_share.py -->
<html lang="he" dir="rtl">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>{title}</title>
<meta name="description" content="{desc}">
<meta property="og:type" content="website">
<meta property="og:locale" content="he_IL">
<meta property="og:site_name" content="דרך הנדיב · מה קורה עכשיו">
<meta property="og:url" content="{url}">
<meta property="og:title" content="{title}">
<meta property="og:description" content="{desc}">
<meta property="og:image" content="{BASE}og-plan.jpg">
<meta property="og:image:width" content="{W}">
<meta property="og:image:height" content="{H}">
<meta property="og:image:alt" content="מפת הפסטיבל עם האירועים המסומנים בכוכב והמסלול ביניהם">
<meta name="twitter:card" content="summary_large_image">
<script>location.replace('{up}' + location.hash);</script>
</head>
<body style="font-family:sans-serif;text-align:center;padding:40px">
<a href="{up}">פתיחת התוכנית בדרך הנדיב</a>
</body>
</html>
'''


def write_pages():
    (ROOT / 'plan').mkdir(exist_ok=True)
    (ROOT / 'plan/index.html').write_text(page())
    for n in range(1, MAX + 1):
        (ROOT / f'plan/{n}').mkdir(exist_ok=True)
        (ROOT / f'plan/{n}/index.html').write_text(page(n))
    print(f'plan/ and plan/1..{MAX}/')


BAND_HTML = '''<!doctype html><html dir="rtl"><head><meta charset="utf-8">
<link href="https://fonts.googleapis.com/css2?family=Rubik:wght@400;500;700;800&display=swap" rel="stylesheet">
<style>
*{{margin:0;box-sizing:border-box}} body{{width:{W}px;height:{H}px;overflow:hidden;font-family:Rubik,sans-serif;background:#1d2b3a}}
.shot{{position:absolute;top:0;left:0;width:{W}px;height:{SH}px;background:url(data:image/png;base64,{img}) top/cover}}
.band{{position:absolute;bottom:0;left:0;right:0;height:{BAND}px;background:#1d2b3a;color:#fff;
  display:flex;align-items:center;gap:26px;padding:0 44px;border-top:5px solid #f6a11b}}
.dot{{width:64px;height:64px;border-radius:50%;background:#f6a11b;display:grid;place-items:center;flex:none;
  font-size:38px;color:#1d2b3a;font-weight:800}}
.dot i{{width:24px;height:24px;border-radius:50%;background:#1d2b3a}}
h1{{font-size:46px;font-weight:800;line-height:1.1}} p{{font-size:25px;color:#c9d4df;margin-top:6px}}
.tag{{margin-inline-start:auto;font-size:24px;font-weight:700;background:#f6a11b;color:#1d2b3a;padding:10px 20px;border-radius:30px;white-space:nowrap}}
</style></head><body><div class="shot"></div>
<div class="band"><div class="dot">{mark}</div><div><h1>{title}</h1><p>{sub}</p></div><div class="tag">{tag}</div></div></body></html>'''


def shots():
    from playwright.sync_api import sync_playwright
    class Quiet(http.server.SimpleHTTPRequestHandler):
        def log_message(self, *a): pass
    handler = functools.partial(Quiet, directory=str(ROOT))
    srv = http.server.ThreadingHTTPServer(('127.0.0.1', 0), handler)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    app = f'http://127.0.0.1:{srv.server_port}/'
    sh = H - BAND
    scale = 0.8                                # the app drawn a little larger than it fits, then shrunk
    with sync_playwright() as p:
        b = p.chromium.launch(channel='chrome')

        def grab(hash_, prep=None, now=NOW_UTC):
            pg = b.new_page(viewport={'width': round(W / scale), 'height': round(sh / scale)}, device_scale_factor=scale)
            pg.clock.set_fixed_time(now)
            pg.goto(app + '#' + hash_)
            pg.wait_for_function('typeof S !== "undefined" && S.events && S.events.length')
            if prep: pg.evaluate(prep)
            pg.wait_for_timeout(4000)          # map tiles and photos
            png = pg.screenshot()
            pg.close()
            return base64.b64encode(png).decode()

        def compose(img, out, **kw):
            pg = b.new_page(viewport={'width': W, 'height': H})
            pg.set_content(BAND_HTML.format(W=W, H=H, SH=sh, BAND=BAND, img=img, **kw))
            pg.wait_for_timeout(1500)          # the font
            pg.screenshot(path=str(ROOT / out), type='jpeg', quality=82)
            pg.close()
            print(out, (ROOT / out).stat().st_size // 1024, 'KB')

        main = grab(f'd={SHOT["day"]}&t={SHOT["t"]}&v=map')
        compose(main, 'og.jpg', mark='<i></i>', title='דרך הנדיב · מה קורה עכשיו',
                sub='כל אירועי הפסטיבל על מפה חיה: מה קורה, איפה, ומה מתחיל עוד מעט', tag='פרדס חנה-כרכור')

        # a plausible afternoon and evening: one after another, each at a different place, all on the map
        prep = '''(() => {
          const day = S.days.find(d => d.slice(8) === '%s');
          const pool = S.events.filter(e => e.date === day && e.vgeo && !e.long).sort((a, b) => a.start - b.start);
          const pick = [], seen = new Set();
          for (const e of pool) {
            if (e.start < 15 * 60 || seen.has(e.vkey)) continue;
            if (pick.length && e.start < pick.at(-1).end + 15) continue;
            pick.push(e); seen.add(e.vkey);
            if (pick.length === 5) break;
          }
          S.plan.clear(); pick.forEach(e => S.plan.add(e.id)); savePlan();
          setView('grid'); redrawAll(); followGrid();
        })()''' % SHOT['day']
        plan = grab(f'd={SHOT["day"]}&v=grid', prep, now='2026-10-30T12:45:00Z')  # 14:45, before the first
        compose(plan, 'og-plan.jpg', mark='★', title='התוכנית שלי בדרך הנדיב',
                sub='האירועים שבחרתי, על המפה ובלוח הזמנים, עם המסלול ביניהם', tag='לצרף לתוכנית שלך')
        b.close()
    srv.shutdown()


if __name__ == '__main__':
    write_pages()
    if '--pages' not in sys.argv:
        shots()
