FILE_TEXT = """== תיאור ==
מפת הבעלויות על הקרקע בפרדס חנה-כרכור של מינהל מקרקעי ישראל, כפי שהובאה באיור 27 של "ניתוח המצב הקיים" לתוכנית המתאר. על המפה עצמה חותמת תאריך מ-2004. בצהוב: קרקע בבעלות פרטית.

== מקור ==
תכנית מתאר מקומית לפרדס חנה כרכור: ניתוח מצב קיים, א.ג. איזן אדריכלים ובוני ערים, 1 באוגוסט 2010, עמ' 59 (מקור המפה לפי המסמך: מינהל מקרקעי ישראל). מסמך ציבורי שהוכן עבור מוסדות התכנון.

== רישיון ==
'''שימוש הוגן.''' המפה מוגנת בזכויות יוצרים ואינה ברישיון חופשי. היא מובאת כאן בשימוש הוגן לפי סעיף 19 לחוק זכות יוצרים, התשס"ח-2007, לצורך תיעוד מסמכי תכנון ציבוריים בערך אנציקלופדי שאינו מסחרי, ברזולוציה נמוכה ובציון המקור. בעל זכויות שמבקש להסיר את המפה מוזמן לכתוב ב[[שיחת משתמש:אורי מוסנזון בוט]].

[[קטגוריה:תכנון ובנייה בפרדס חנה-כרכור]]
"""

ARTS = {"חקלאות בפרדס חנה-כרכור": lambda: AGRI, "בעלות על הקרקע בפרדס חנה-כרכור": own_text}

def upload(c):
    title = "בעלות על הקרקע בפרדס חנה-כרכור - מפת בעלויות.jpg"
    with open(os.path.join(IMG, "own.jpg"), "rb") as fh:
        r = c.session.post("https://pardespedia.info/api.php", data={
            "action": "upload", "filename": title, "token": c._csrf_token(), "format": "json",
            "comment": "מפת בעלויות מתוך ניתוח המצב הקיים של תוכנית המתאר, שימוש הוגן", "text": FILE_TEXT},
            files={"file": (title, fh, "image/jpeg")}).json()
    print(title, r.get("upload", {}).get("result"), r.get("error") or r.get("upload", {}).get("warnings"))

if __name__ == "__main__":
    if sys.argv[1] == "print":
        for k, f in ARTS.items(): print("=====", k); print(f())
    else:
        c = WikiClient(); c.login()
        upload(c)
        for k, f in ARTS.items():
            print(c.edit_page(k, f(), summary="ערך חדש מתוך ניתוח המצב הקיים של תוכנית המתאר (2010)", create_only=True))
