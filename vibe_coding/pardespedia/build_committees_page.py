def table(rows_wikitext, header, empty_note):
    out = ['<div style="overflow-x:auto;">',
           '{| class="wikitable sortable" style="width:100%"', header]
    out += rows_wikitext if rows_wikitext else []
    out += ['|}', '</div>']
    if not rows_wikitext:
        out.append('')
        out.append(empty_note)
    return '\n'.join(out)


