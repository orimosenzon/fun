def with_phone(entry: str) -> str:
    """Append the published phone to a member line, matching on the bare name."""
    import re as _re
    bare = _re.sub(r'\[\[([^\]|]+)\|?([^\]]*)\]\]', lambda m: m.group(2) or m.group(1), entry)
    bare = bare.split(',')[0].split(' / ')[0].strip()
    bare = _re.sub(r'^(עו"ד|ד"ר)\s+', '', bare).strip()
    tel = PHONES.get(bare)
    return entry + (' · ' + tel if tel else '')


