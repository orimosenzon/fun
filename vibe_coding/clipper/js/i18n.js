C.lang = (() => {
  try { const l = localStorage.getItem('clipper.lang'); if (l === 'he' || l === 'en') return l; } catch {}
  return (navigator.language || '').toLowerCase().startsWith('he') ? 'he' : 'en';
})();

C.t = (key, ...args) => {
  const v = (C.STR[C.lang] && C.STR[C.lang][key]) ?? C.STR.en[key] ?? key;
  return typeof v === 'function' ? v(...args) : v;
};

C.applyI18n = () => {
  document.documentElement.lang = C.lang;
  document.documentElement.dir = C.lang === 'he' ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = C.t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = C.t(el.dataset.i18nTitle); });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = C.t(el.dataset.i18nPh); });
  document.title = C.t('appName');
  const b = document.getElementById('btnLang');
  if (b) b.textContent = C.lang === 'he' ? 'English' : 'עברית';
};

C.setLang = (l) => {
  C.lang = l;
  try { localStorage.setItem('clipper.lang', l); } catch {}
  C.applyI18n();
};
